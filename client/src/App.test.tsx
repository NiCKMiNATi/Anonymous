import { render, screen, waitFor, within } from "@testing-library/react";
import userEvent from "@testing-library/user-event";
import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";
import { App } from "./App";
import { FakeBackend } from "./test/fakeBackend";

let backend: FakeBackend;

beforeEach(() => {
  backend = new FakeBackend();
  vi.stubGlobal("fetch", backend.fetch);
  window.location.hash = "";
});

afterEach(() => {
  vi.unstubAllGlobals();
});

async function openApp() {
  const user = userEvent.setup();
  const view = render(<App />);
  return { user, ...view };
}

describe("Anonymous chat client", () => {
  it("shows the app title, the no-authentication notice and an empty state", async () => {
    await openApp();
    expect(screen.getByRole("heading", { name: "Anonymous", level: 1 })).toBeInTheDocument();
    expect(screen.getByText(/no authentication yet/i)).toBeInTheDocument();
    expect(await screen.findByText(/Create a conversation to get started/i)).toBeInTheDocument();
  });

  it("creates a conversation, sends a message and shows both messages with visible times", async () => {
    const { user, container } = await openApp();
    await user.click(await screen.findByRole("button", { name: "New conversation" }));

    const input = await screen.findByLabelText("Message");
    await user.type(input, "hello");
    await user.click(screen.getByRole("button", { name: "Send" }));

    expect(await screen.findByText("Fake reply to: hello")).toBeInTheDocument();
    const [userMessage, assistantMessage] = screen.getAllByRole("listitem").filter((li) =>
      li.classList.contains("message"),
    );
    expect(within(userMessage!).getByText("hello")).toBeInTheDocument();
    expect(within(assistantMessage!).getByText(/Generated by fake-echo-1/)).toBeInTheDocument();

    // Times are rendered continuously (no hover) and carry the server's absolute instants.
    const times = Array.from(container.querySelectorAll(".message time"));
    expect(times).toHaveLength(2);
    const stored = backend.details.get(backend.conversations[0]!.id)!.messages;
    expect(times.map((t) => t.getAttribute("dateTime"))).toEqual(stored.map((m) => m.committed_at));
    for (const time of times) {
      expect(time).toBeVisible();
      expect(time.textContent).toMatch(/\d/);
      expect(time.getAttribute("title")).toBeTruthy(); // precise secondary detail
    }
    expect(input).toHaveValue("");
  });

  it("shows a generating state while the send is in flight and the user message as unsaved", async () => {
    let release!: () => void;
    backend.holdSends = new Promise<void>((resolve) => (release = resolve));
    backend.seed("Chat");
    const { user } = await openApp();
    await user.type(await screen.findByLabelText("Message"), "slow one{Enter}");

    expect(await screen.findByRole("status", { name: "" })).toHaveTextContent("Generating response…");
    const pending = screen.getByTestId("pending-message");
    expect(pending).toHaveTextContent("Sending…");
    expect(screen.getByRole("button", { name: "Send" })).toBeDisabled();

    release();
    expect(await screen.findByText("Fake reply to: slow one")).toBeInTheDocument();
    expect(screen.queryByTestId("pending-message")).not.toBeInTheDocument();
  });

  it("still shows the conversation and messages after a reload", async () => {
    backend.seed("Persisted chat");
    const first = await openApp();
    await first.user.type(await screen.findByLabelText("Message"), "remember me{Enter}");
    await screen.findByText("Fake reply to: remember me");
    first.unmount();

    await openApp(); // a fresh client against the same server state; the hash keeps the selection
    expect(await screen.findByText("remember me")).toBeInTheDocument();
    expect(screen.getByText("Fake reply to: remember me")).toBeInTheDocument();
    expect(screen.getByRole("heading", { name: "Persisted chat", level: 2 })).toBeInTheDocument();
  });

  it("renders messages in the server's authoritative order, not by timestamp", async () => {
    const conversation = backend.seed("Order");
    backend.details.get(conversation.id)!.messages.push(
      {
        id: "m1", position: 1, role: "user", content: "FIRST",
        committed_at: "2026-01-15T12:00:09Z", produced_by_run_id: null,
      },
      {
        id: "m2", position: 2, role: "assistant", content: "SECOND",
        committed_at: "2026-01-15T12:00:01Z", produced_by_run_id: null, // earlier time, later position
      },
    );
    await openApp();
    await screen.findByText("FIRST");
    const bodies = Array.from(document.querySelectorAll(".message__body")).map((n) => n.textContent);
    expect(bodies).toEqual(["FIRST", "SECOND"]);
  });

  it("shows a clear failure state and no assistant message when generation fails", async () => {
    backend.failGeneration = true;
    backend.seed("Failing");
    const { user } = await openApp();
    await user.type(await screen.findByLabelText("Message"), "will fail{Enter}");

    const alert = await screen.findByRole("alert");
    expect(alert).toHaveTextContent("Response failed");
    expect(alert).toHaveTextContent("The fake model was asked to fail.");
    expect(screen.getByText("will fail")).toBeInTheDocument(); // the user message is kept
    expect(document.querySelectorAll(".message--assistant")).toHaveLength(0);
    expect(screen.getByRole("button", { name: "Send" })).toBeDisabled(); // empty draft only
  });

  it("does not send empty or whitespace-only messages", async () => {
    backend.seed("Empty");
    const { user } = await openApp();
    const input = await screen.findByLabelText("Message");
    const send = screen.getByRole("button", { name: "Send" });
    expect(send).toBeDisabled();
    await user.type(input, "   ");
    expect(send).toBeDisabled();
    await user.type(input, "{Enter}");
    expect(backend.sendCalls).toHaveLength(0);
  });

  it("reports an unreachable server and recovers when it comes back", async () => {
    backend.down = true;
    const { user } = await openApp();
    expect(await screen.findByText(/Cannot reach the Anonymous server/i)).toBeInTheDocument();

    backend.down = false;
    backend.seed("Back online");
    await user.click(screen.getByRole("button", { name: "Retry" }));
    expect(await screen.findByRole("heading", { name: "Back online", level: 2 })).toBeInTheDocument();
    expect(screen.queryByText(/Cannot reach the Anonymous server/i)).not.toBeInTheDocument();
  });

  it("keeps an unconfirmed message and retries it with the same submission id (no duplicate)", async () => {
    backend.seed("Lossy");
    backend.loseNextAcknowledgment = true;
    const { user } = await openApp();
    await user.type(await screen.findByLabelText("Message"), "did you get this{Enter}");

    expect(await screen.findByText("Not confirmed saved")).toBeInTheDocument();
    const pending = screen.getByTestId("pending-message");
    expect(within(pending).getByRole("alert")).toHaveTextContent(/Retrying is safe/);
    expect(screen.getAllByText(/Cannot reach the Anonymous server/i).length).toBeGreaterThan(0);

    await user.click(screen.getByRole("button", { name: "Retry sending" }));
    expect(await screen.findByText("Fake reply to: did you get this")).toBeInTheDocument();

    expect(screen.queryByText(/Cannot reach the Anonymous server/i)).not.toBeInTheDocument();
    expect(backend.sendCalls).toHaveLength(2);
    expect(backend.sendCalls[1]!.submissionId).toBe(backend.sendCalls[0]!.submissionId);
    const stored = backend.details.get(backend.conversations[0]!.id)!.messages;
    expect(stored.filter((m) => m.role === "user")).toHaveLength(1);
    expect(document.querySelectorAll(".message--user:not(.message--pending)")).toHaveLength(1);
  });

  it("shows a refusal (e.g. busy) and restores the draft without pretending it was sent", async () => {
    backend.seed("Busy");
    backend.refuseNextSend = {
      status: 409,
      code: "conversation_busy",
      message: "A response is already being generated or is unresolved for this conversation.",
    };
    const { user } = await openApp();
    await user.type(await screen.findByLabelText("Message"), "too soon{Enter}");

    expect(await screen.findByRole("alert")).toHaveTextContent(/already being generated/);
    expect(screen.getByLabelText("Message")).toHaveValue("too soon");
    expect(screen.queryByTestId("pending-message")).not.toBeInTheDocument();
    expect(document.querySelectorAll(".message--user")).toHaveLength(0);
  });

  it("pauses sending while the server reports an unsettled response", async () => {
    const conversation = backend.seed("Unsettled");
    backend.details.get(conversation.id)!.messages.push({
      id: "m1", position: 1, role: "user", content: "left hanging",
      committed_at: "2026-01-15T12:00:00Z", produced_by_run_id: null,
    });
    backend.details.get(conversation.id)!.runs.push({
      id: "r1", triggering_message_id: "m1", status: "indeterminate",
      model_id: "m", runtime_id: "r", failure_code: null, failure_message: null,
    });
    await openApp();
    expect(await screen.findByText(/sending is paused/i)).toBeInTheDocument();
    await waitFor(() => expect(screen.getByRole("button", { name: "Send" })).toBeDisabled());
  });

  it("switches between conversations", async () => {
    const a = backend.seed("Alpha");
    backend.seed("Beta");
    backend.details.get(a.id)!.messages.push({
      id: "ma", position: 1, role: "user", content: "alpha content",
      committed_at: "2026-01-15T12:00:00Z", produced_by_run_id: null,
    });
    const { user } = await openApp();
    await screen.findByRole("heading", { name: "Beta", level: 2 }); // most recent first
    await user.click(screen.getByRole("button", { name: /Alpha/ }));
    expect(await screen.findByText("alpha content")).toBeInTheDocument();
    expect(screen.getByRole("button", { name: /Alpha/ })).toHaveAttribute("aria-current", "true");
  });
});
